/**
 * Records a real provider answer per seeded string, so the seed is a recording
 * rather than a special case.
 *
 * It calls `buildPrompt` and `createGeminiClient` — the production prompt and
 * the production client, the same pair the eval runner uses — and writes
 * `src/db/content.generated.ts`. A developer reads the diff and commits it.
 * Seeded rows and looked-up rows are then indistinguishable, because they were
 * made the same way: `db/seed.ts` replays this through `persistEntries`.
 *
 * It lives here rather than in `scripts/` because ADR 0001 R11 exempts exactly
 * two directories from "providers/ is constructed only at the composition
 * root", and this bucket is already one of them — ADR 0004 R4 defines
 * `tests/eval/` as the opt-in real-model code, which describes a recorder
 * exactly. It is not an eval and is not scored; it shares the bucket because it
 * shares the provider client.
 *
 * Not named *.test.ts, so neither Jest project can pick it up.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import type { LlmTranslation } from '@lang-tutor/core/api';

import { loadGeminiConfig } from '../../src/config';
import { content } from '../../src/db/content';
import { recorded } from '../../src/db/content.generated';
import { createGeminiClient } from '../../src/providers/gemini';
import { askModel } from './askModel';

const TIMEOUT_MS = 30_000;
const OUTPUT = join(__dirname, '..', '..', 'src', 'db', 'content.generated.ts');

const HEADER = `// Recorded provider answers, one per seeded string. Generated by
// \`npm run content:generate\` and reviewed by hand; db/seed.ts replays these
// through persistEntries, the same write path a lookup uses, which is why a
// seeded row and a looked-up row are indistinguishable.
//
// DO NOT EDIT BY HAND. Re-record one string with
// \`npm run content:generate -- <query>\`, read the diff, and commit it.
import type { LlmTranslation } from '@lang-tutor/core/api';

export const recorded: Record<string, LlmTranslation> = `;

async function main(): Promise<void> {
  const gemini = loadGeminiConfig(process.env);
  if (gemini.baseUrl.includes('localhost') || gemini.baseUrl.includes('127.0.0.1')) {
    throw new Error(
      `GEMINI_BASE_URL points at ${gemini.baseUrl}. A recording must come from the real ` +
        'API; unset it to use the default.',
    );
  }

  // A filter, and a merge rather than a replace. Without it every re-record
  // produces a thirteen-entry diff that nobody reads carefully — regeneration
  // is non-deterministic enough at temperature 0 that wording shifts across
  // the whole file, and a reviewer skimming noise is how a bad recording gets
  // committed. With no filter it re-records everything, which is the
  // deliberate act.
  const filter = process.argv[2];
  const queries = content
    .map((entry) => entry.query)
    .filter((query) => !filter || query === filter);

  if (queries.length === 0) {
    throw new Error(
      `no seeded query matches "${filter}". Known queries:\n  ` +
        content.map((entry) => entry.query).join('\n  '),
    );
  }

  // Every placeholder entry has exactly one sense and no example — the
  // authored source in `db/content.ts` never had one to record, and the
  // prompt above always asks the model for one on a real word or phrase. So
  // "not a single example anywhere in the file yet" is the one condition
  // that tells a still-placeholder file apart from a genuinely recorded one,
  // with no separate marker field needed. A filtered run against a
  // still-placeholder file would record just `filter` for real and then
  // stamp the "DO NOT EDIT BY HAND" header (below) over every other query,
  // falsely marking untouched placeholders as reviewed recordings.
  const stillPlaceholder = Object.values(recorded).every((translation) =>
    translation.entries.every((entry) => entry.senses.every((sense) => !sense.example)),
  );
  if (filter && stillPlaceholder) {
    throw new Error(
      `content.generated.ts is still all placeholders — content:generate has never recorded ` +
        `for real. The first run must be unfiltered ("npm run content:generate", no query ` +
        `argument) so every one of the ${content.length} queries gets a genuine recording; ` +
        `running it filtered right now would record only "${filter}" for real and then stamp ` +
        'the "DO NOT EDIT BY HAND" header over the other ' +
        `${content.length - 1} placeholders, marking them as reviewed recordings they are not.`,
    );
  }

  const llm = createGeminiClient({
    fetch: globalThis.fetch,
    baseUrl: gemini.baseUrl,
    apiKey: gemini.apiKey,
    model: gemini.model,
    timeoutMs: TIMEOUT_MS,
  });

  // Sequential: thirteen calls at a few seconds each, against a modest quota.
  // A burst that trips a per-minute limit would poison the recording with a
  // 429 rather than merely slowing it down.
  //
  // A filtered run must preserve every entry it does not touch, so it starts
  // from the existing `recorded` map and the loop below overwrites only the
  // named query. An unfiltered run starts empty instead: `queries` is then
  // every query `content` currently lists, and the loop fills `next` from
  // that list alone, so a query since removed from `content` is pruned
  // rather than carried over from the stale `recorded` map. Do not collapse
  // these into one `{ ...recorded }` start — that is exactly what silently
  // reintroduces orphaned entries on an unfiltered re-record.
  const next: Record<string, LlmTranslation> = filter ? { ...recorded } : {};
  for (const query of queries) {
    const answer = await askModel(llm, { text: query });
    // A sentence is never persisted by a real lookup
    // (`services/translations.ts`), so recording one here would let
    // `db/seed.ts` store a dictionary row no lookup could ever have
    // produced — the failure mode this phase's indistinguishability claim
    // depends on not happening. Caught here, at record time, while a human
    // is watching the output and can fix the query rather than the data.
    if (answer.kind === 'sentence') {
      throw new Error(
        `content:generate classified "${query}" as a sentence, which must never be recorded: ` +
          'a sentence is never persisted by a real lookup, so seeding one would create a row ' +
          'no lookup could have created. Reword the query in db/content.ts so the model reads ' +
          'it as a word or phrase, then re-run.',
      );
    }
    next[query] = { kind: answer.kind, entries: answer.entries };
    const shape = answer.entries
      .map((entry) => `${entry.lemma}(${entry.senses.length})`)
      .join(' ');
    console.log(`  ${query} -> ${answer.kind} ${shape || '(no entries)'}`);
  }

  writeFileSync(OUTPUT, `${HEADER}${JSON.stringify(next, null, 2)};\n`);
  console.log(`\nrecorded ${queries.length} of ${content.length} into ${OUTPUT}`);
  console.log('Read the diff before committing.');
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
